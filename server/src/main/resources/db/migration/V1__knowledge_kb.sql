-- V1 지식: 법령·안내서 원문(D1~D7). 채우는 것: data/out/mysql/10_kb.sql
-- 칸 이름·순서는 build/db/schema.sql(SQLite)과 같다. 다른 곳(06 2.2·2.3): 키 칸 utf8mb4_bin, 시각 DATETIME(3) UTC,
-- 날짜 DATE, JSON 글은 JSON 형, kb_chunks.embedding NULL 허용·chunk_key UNIQUE.
-- 적재 파일 사이 FK는 걸지 않는다(이 파일 안의 FK만). 빠진 참조는 기동 때 지식 스냅샷이 확인한다(06 3.1).

CREATE TABLE kb_documents (
  doc_id            INT          NOT NULL,
  source_type       VARCHAR(10)  NOT NULL,
  title             VARCHAR(200) NOT NULL,
  law_name          VARCHAR(200) NOT NULL,
  law_id            VARCHAR(20),
  law_serial_no     VARCHAR(30),
  case_no           VARCHAR(40),
  promulgation_date DATE,
  effective_date    DATE,
  stage             INT          NOT NULL,
  url               VARCHAR(500),
  content_hash      CHAR(64),
  sync_source       VARCHAR(20)  NOT NULL DEFAULT 'LAW_API',
  verified          TINYINT(1)   NOT NULL DEFAULT 0,
  last_checked_at   DATETIME(3),
  created_at        DATETIME(3)  NOT NULL,
  law_kind          VARCHAR(10)  NOT NULL,
  api_target        VARCHAR(10),
  promulgation_no   VARCHAR(20),
  parent_doc_id     INT,
  use_policy        VARCHAR(12),
  use_scope         JSON,
  use_policy_by     VARCHAR(20),
  use_policy_at     DATE,
  use_policy_note   TEXT,
  guide_version     VARCHAR(20),
  page_count        INT,
  excluded_pages    JSON,
  PRIMARY KEY (doc_id),
  CONSTRAINT ck_kb_documents_policy CHECK (use_policy IS NULL OR use_policy IN ('ANSWER_BASIS','REFERENCE','OUT')),
  CONSTRAINT fk_kb_documents_parent FOREIGN KEY (parent_doc_id) REFERENCES kb_documents (doc_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='법령·안내서 문서';

CREATE TABLE guide_sections (
  section_id      VARCHAR(20)  COLLATE utf8mb4_bin NOT NULL,
  doc_id          INT          NOT NULL,
  parent_id       VARCHAR(20)  COLLATE utf8mb4_bin,
  depth           INT          NOT NULL,
  title           VARCHAR(300) NOT NULL,
  path            JSON         NOT NULL,
  path_text       VARCHAR(1000) NOT NULL,
  ord             INT          NOT NULL,
  num             VARCHAR(40)  NOT NULL,
  is_leaf         TINYINT(1)   NOT NULL,
  synthetic       TINYINT(1)   NOT NULL,
  page_from       INT,
  page_to         INT,
  chunk_from      INT,
  chunk_to        INT,
  chunk_count     INT          NOT NULL,
  own_chunk_count INT          NOT NULL,
  char_count      INT          NOT NULL,
  chunk_runs      INT          NOT NULL,
  PRIMARY KEY (section_id),
  KEY idx_section_doc (doc_id, ord),
  CONSTRAINT fk_guide_sections_doc FOREIGN KEY (doc_id) REFERENCES kb_documents (doc_id),
  CONSTRAINT fk_guide_sections_parent FOREIGN KEY (parent_id) REFERENCES guide_sections (section_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='안내서 절 목록(D7)';
-- SQLite의 UNIQUE(doc_id, path)는 JSON 칸이라 MySQL에서 걸 수 없다. path_text는 같은 뜻이지만 길어서 색인하지 않는다(빌드가 이미 지킴).

CREATE TABLE kb_chunks (
  chunk_id       INT          NOT NULL,
  doc_id         INT          NOT NULL,
  article        VARCHAR(300) NOT NULL,
  text           TEXT         NOT NULL,
  embedding      MEDIUMBLOB,
  status         VARCHAR(10)  NOT NULL,
  effective_from DATE,
  effective_to   DATE,
  replaced_by    INT,
  text_hash      CHAR(64)     NOT NULL,
  verified       TINYINT(1)   NOT NULL DEFAULT 0,
  unit_key       VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
  jo             INT,
  jo_sub         INT          DEFAULT 0,
  hang           INT,
  ho             VARCHAR(20),
  ho_from        VARCHAR(20),
  ho_to          VARCHAR(20),
  mok            VARCHAR(20),
  title          VARCHAR(200),
  source_file    VARCHAR(300) NOT NULL,
  chunk_key      VARCHAR(100) COLLATE utf8mb4_bin,
  section_id     VARCHAR(20)  COLLATE utf8mb4_bin,
  page_from      INT,
  page_to        INT,
  PRIMARY KEY (chunk_id),
  UNIQUE KEY uk_kb_chunks_unit (unit_key, status, effective_from),
  UNIQUE KEY uk_kb_chunks_key (chunk_key),
  KEY idx_chunk_section (section_id),
  KEY idx_chunk_doc (doc_id, status),
  KEY idx_chunk_jo (doc_id, jo, jo_sub, hang),
  CONSTRAINT ck_kb_chunks_status CHECK (status IN ('CURRENT','PENDING','ARCHIVED')),
  CONSTRAINT fk_kb_chunks_doc FOREIGN KEY (doc_id) REFERENCES kb_documents (doc_id),
  CONSTRAINT fk_kb_chunks_section FOREIGN KEY (section_id) REFERENCES guide_sections (section_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='조문·안내서 청크';
-- SQLite idx_chunk_article(article)은 지식을 DB에서 찾지 않으므로(06 6.2) 두지 않는다.

CREATE TABLE kb_annexes (
  annex_id       INT          NOT NULL,
  doc_id         INT          NOT NULL,
  annex_key      VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
  kind           VARCHAR(10)  NOT NULL,
  annex_no       INT          NOT NULL,
  annex_sub      INT          NOT NULL DEFAULT 0,
  label          VARCHAR(60)  NOT NULL,
  title          VARCHAR(300),
  text           MEDIUMTEXT,
  text_rows      MEDIUMTEXT,
  status         VARCHAR(10)  NOT NULL,
  effective_from DATE,
  text_hash      CHAR(64),
  pdf_link       VARCHAR(300),
  file_link      VARCHAR(300),
  related        VARCHAR(200),
  source_file    VARCHAR(300) NOT NULL,
  PRIMARY KEY (annex_id),
  UNIQUE KEY uk_kb_annexes_key (annex_key, status, effective_from),
  CONSTRAINT fk_kb_annexes_doc FOREIGN KEY (doc_id) REFERENCES kb_documents (doc_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='별표·서식';

CREATE TABLE kb_links (
  link_id           INT          NOT NULL,
  link_type         VARCHAR(10)  NOT NULL,
  src_key           VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
  src_chunk_id      INT,
  src_annex_id      INT,
  dst_key           VARCHAR(200) COLLATE utf8mb4_bin NOT NULL,
  dst_doc_id        INT,
  dst_chunk_id      INT,
  dst_annex_id      INT,
  resolution        VARCHAR(10)  NOT NULL,
  unresolved_reason VARCHAR(40),
  evidence          TEXT,
  origin            VARCHAR(20)  NOT NULL,
  PRIMARY KEY (link_id),
  KEY idx_link_src (src_chunk_id),
  KEY idx_link_dst (dst_chunk_id),
  CONSTRAINT ck_kb_links_type CHECK (link_type IN ('본문참조','위임','별표','준용')),
  CONSTRAINT fk_kb_links_src_chunk FOREIGN KEY (src_chunk_id) REFERENCES kb_chunks (chunk_id),
  CONSTRAINT fk_kb_links_src_annex FOREIGN KEY (src_annex_id) REFERENCES kb_annexes (annex_id),
  CONSTRAINT fk_kb_links_dst_doc FOREIGN KEY (dst_doc_id) REFERENCES kb_documents (doc_id),
  CONSTRAINT fk_kb_links_dst_chunk FOREIGN KEY (dst_chunk_id) REFERENCES kb_chunks (chunk_id),
  CONSTRAINT fk_kb_links_dst_annex FOREIGN KEY (dst_annex_id) REFERENCES kb_annexes (annex_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='조문 연결';

CREATE TABLE build_info (
  k VARCHAR(60) COLLATE utf8mb4_bin NOT NULL,
  v TEXT        NOT NULL,
  PRIMARY KEY (k)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='빌드 정보';
